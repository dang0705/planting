CREATE TABLE `security_audit_records` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '安全审计记录内部主键',
  `_openid` VARCHAR(64) NOT NULL DEFAULT '' COMMENT 'CloudBase 技术兼容字段，服务端表固定为空，不作为用户归属',
  `audit_ref` VARCHAR(64) NOT NULL COMMENT '高熵审计记录引用',
  `principal_type` VARCHAR(16) NOT NULL COMMENT '主体类型：guest、user、service',
  `principal_safe_ref` VARCHAR(64) NOT NULL COMMENT '脱敏主体引用，不含平台标识',
  `action` VARCHAR(96) NOT NULL COMMENT '受控动作代码',
  `object_type` VARCHAR(64) NOT NULL COMMENT '对象类型',
  `object_public_ref` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '对象公开引用，无对象时为空',
  `result` VARCHAR(24) NOT NULL COMMENT '结果：allowed、denied、failed',
  `reason_code` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '脱敏原因代码',
  `occurred_at_ms` BIGINT UNSIGNED NOT NULL COMMENT '发生时间，UTC 毫秒',
  `created_at_ms` BIGINT UNSIGNED NOT NULL COMMENT '创建时间，UTC 毫秒',
  `updated_at_ms` BIGINT UNSIGNED NOT NULL COMMENT '更新时间，UTC 毫秒',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_security_audit_ref` (`audit_ref`),
  KEY `idx_security_audit_subject` (`principal_type`, `principal_safe_ref`, `occurred_at_ms`),
  KEY `idx_security_audit_object` (`object_type`, `object_public_ref`, `occurred_at_ms`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='青花植 v2 脱敏安全审计记录';
