-- 青花植后端 v2 / 各写域可靠事件与安全审计空库 DDL。
-- 每个业务域拥有独立 outbox，禁止跨域直接写对方表。

CREATE TABLE `identity_outbox` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT 'identity 事件内部主键',
  `_openid` VARCHAR(64) NOT NULL DEFAULT '' COMMENT 'CloudBase 技术兼容字段，服务端表固定为空，不作为用户归属',
  `event_id` VARCHAR(64) NOT NULL COMMENT '全局高熵事件标识',
  `aggregate_ref` VARCHAR(64) NOT NULL COMMENT '聚合公开引用',
  `aggregate_version` INT UNSIGNED NOT NULL COMMENT '聚合版本',
  `event_type` VARCHAR(96) NOT NULL COMMENT '版本化事件类型',
  `schema_version` VARCHAR(32) NOT NULL COMMENT '事件结构版本',
  `payload_json` JSON NOT NULL COMMENT '脱敏事件载荷',
  `payload_hash` CHAR(64) NOT NULL COMMENT '规范化载荷 SHA-256',
  `status` VARCHAR(24) NOT NULL COMMENT '状态：pending、dispatching、delivered、dead_letter',
  `lease_owner` VARCHAR(64) NULL COMMENT '当前派发租约持有者',
  `lease_until_ms` BIGINT UNSIGNED NULL COMMENT '租约失效时间，UTC 毫秒',
  `attempt_count` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '派发尝试次数',
  `next_attempt_at_ms` BIGINT UNSIGNED NOT NULL COMMENT '下次派发时间，UTC 毫秒',
  `occurred_at_ms` BIGINT UNSIGNED NOT NULL COMMENT '业务发生时间，UTC 毫秒',
  `delivered_at_ms` BIGINT UNSIGNED NULL COMMENT '成功投递时间，UTC 毫秒',
  `created_at_ms` BIGINT UNSIGNED NOT NULL COMMENT '创建时间，UTC 毫秒',
  `updated_at_ms` BIGINT UNSIGNED NOT NULL COMMENT '更新时间，UTC 毫秒',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_identity_outbox_event` (`event_id`),
  UNIQUE KEY `uq_identity_outbox_version` (`aggregate_ref`, `aggregate_version`, `event_type`),
  KEY `idx_identity_outbox_dispatch` (`status`, `next_attempt_at_ms`, `lease_until_ms`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='青花植 v2 identity 可靠事件发件箱';

